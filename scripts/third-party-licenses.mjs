/* Collect the licence text of every crate the Windows binary links, and write
 * it to THIRD-PARTY-LICENSES.md.
 *
 * Why this file has to exist: Hangboard ships as a compiled .exe, and MIT — the
 * licence of most of the dependency graph — requires the copyright notice and
 * permission notice to travel with every copy of the binary. Putting the
 * notices in the repository is not enough; they have to be reachable from the
 * download. `bundle.licenseFile` in tauri.conf.json points the NSIS installer at
 * LICENSE, and this file is the long tail behind it.
 *
 * The output groups crates by identical licence text so the MIT body appears
 * once with a list of who it covers, instead of hundreds of times.
 *
 *   node scripts/third-party-licenses.mjs           # write the file
 *   node scripts/third-party-licenses.mjs --check   # fail if it is stale
 */

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const root = path.resolve(import.meta.dirname, "..");
const outFile = path.join(root, "THIRD-PARTY-LICENSES.md");
const checkOnly = process.argv.includes("--check");

/* ---- what is actually linked ------------------------------------------- */

const meta = JSON.parse(
  execFileSync(
    "cargo",
    [
      "metadata",
      "--format-version",
      "1",
      // Windows-only, because the rest of the graph is not in the binary. The
      // unfiltered graph carries 54 extra crates (objc2, ndk, gbm, gl,
      // libappindicator) for platforms this app does not build for; listing
      // their licences would misstate what ships.
      "--filter-platform",
      "x86_64-pc-windows-msvc",
      "--manifest-path",
      "src-tauri/Cargo.toml",
    ],
    {
      cwd: root,
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
    },
  ),
);

// The workspace crate itself is not a third party.
const packages = meta.packages.filter((p) => p.name !== "hangboard");

/* ---- find each crate's licence text on disk ---------------------------- */

const LICENSE_NAMES = /^(licen[cs]e|copying|notice)([-._].*)?$/i;

function readLicenceText(pkg) {
  const dir = path.dirname(pkg.manifest_path);
  let entries;
  try {
    entries = fs.readdirSync(dir);
  } catch {
    return null;
  }
  const files = entries.filter((n) => LICENSE_NAMES.test(n)).sort();
  if (!files.length) return null;
  return files
    .map((n) => {
      let body = fs.readFileSync(path.join(dir, n), "utf8");
      body = body.replace(/\r\n/g, "\n").trim();
      return `--- ${pkg.name} ${pkg.version}: ${n} ---\n\n${body}`;
    })
    .join("\n\n");
}

const groups = new Map(); // licence text -> [{name, version, spdx}]
const missing = [];

for (const pkg of packages) {
  const text = readLicenceText(pkg);
  const spdx = pkg.license ?? "unknown";
  if (!text) {
    missing.push(`${pkg.name} ${pkg.version} (${spdx})`);
    continue;
  }
  // Key on the body with the per-crate header stripped, so identical licences
  // collapse together.
  const bodyKey = text.replace(/^--- .* ---$/gm, "").trim();
  if (!groups.has(bodyKey)) groups.set(bodyKey, []);
  groups.get(bodyKey).push({ name: pkg.name, version: pkg.version, spdx });
}

/* ---- render ------------------------------------------------------------ */

const lines = [];
lines.push("# Third-party licences");
lines.push("");
lines.push(
  "Hangboard is MIT (see [LICENSE](LICENSE)). It links the crates below, and",
  "their licences require their notices to travel with the compiled binary.",
);
lines.push("");
lines.push(
  `Generated by \`npm run licenses\` from \`cargo metadata\` — ${packages.length} crates,`,
);
lines.push(`${groups.size} distinct licence texts. Do not edit by hand.`);
lines.push("");

const sorted = [...groups.entries()].sort((a, b) => b[1].length - a[1].length);

for (const [text, crates] of sorted) {
  crates.sort((a, b) => a.name.localeCompare(b.name));
  const spdxSet = new Set(crates.map((c) => c.spdx));
  lines.push(`## ${[...spdxSet].sort().join(" / ")} — ${crates.length} crate(s)`);
  lines.push("");
  lines.push(crates.map((c) => `- \`${c.name}\` ${c.version}`).join("\n"));
  lines.push("");
  lines.push("```");
  lines.push(text);
  lines.push("```");
  lines.push("");
}

if (missing.length) {
  lines.push("## Crates with no licence file on disk");
  lines.push("");
  lines.push(
    "These declare a licence in their manifest but ship no licence file. Their",
    "SPDX identifier is listed; the text is available from crates.io.",
  );
  lines.push("");
  lines.push(missing.sort().map((m) => `- ${m}`).join("\n"));
  lines.push("");
}

const rendered = lines.join("\n");

/* ---- write or verify --------------------------------------------------- */

if (checkOnly) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
  if (current !== rendered) {
    console.error("✗ THIRD-PARTY-LICENSES.md is stale — run `npm run licenses`");
    process.exit(1);
  }
  console.log(`third-party licences ok — ${packages.length} crates, ${groups.size} texts`);
} else {
  fs.writeFileSync(outFile, rendered);
  const kb = (Buffer.byteLength(rendered) / 1024).toFixed(0);
  console.log(
    `wrote THIRD-PARTY-LICENSES.md — ${packages.length} crates, ${groups.size} texts, ${kb} KB` +
      (missing.length ? `, ${missing.length} without a file` : ""),
  );
}
